import logging
import requests

API_URL = "https://gigachat.api.example/v1/chat/completions"
config = {"gigachat": {"model": "GigaChat"}}

def review_test_case_by_gigachat(prompt, token):
    try:
        payload = {
            "model": f"{config['gigachat']['model']}:latest",
            "messages": [{"role": "user", "content": prompt}],
            "temperature": 0.7,
            "top_p": 0.9,
            "safe_mode": False,
            "profanity_check": False,
            "stream": False,
        }

        headers = {
            "Content-Type": "application/json",
            "Authorization": f"Bearer {token}",
        }

        response = requests.post(
            API_URL, json=payload, headers=headers, verify=False, timeout=60
        )

        if response.status_code == 200:
            return response.json()
        else:
            logging.error(
                f"❌ Ошибка GigaChat ({response.status_code}): {response.text}"
            )
            return None

    except Exception as e:
        logging.error(f"❌ Ошибка при анализе задач в GigaChat: {e}")
        return None


